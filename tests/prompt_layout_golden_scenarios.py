class _FrozenDatetime(datetime):
    """The web date line (runtime-fixes-20261110 T2) reads the wall clock when no
    ``clock_now`` is given; the goldens freeze it so they stay byte-stable."""

    @classmethod
    def now(cls, tz=None):
        return CLOCK


def run_all(layout_kw):
    from unittest import mock

    with mock.patch.object(pa, "datetime", _FrozenDatetime):
        return _run_all(layout_kw)


def _run_all(layout_kw):
    out = {}
    for name, (text, source, extra) in SCENARIOS.items():
        i18n_active.reset_active_bundle()
        _activate("es")
        kw = dict(
            system_prompt=PERSONAS["es"],
            use_system_role=True,
            is_local=True,
            provider_cfg={},
            request_model="llama3",
            history_snapshot=list(HISTORY),
            personalization_enabled=False,
            memorias_enabled=False,
        )
        kw.update(extra)
        setup = pa.PromptContextAssembler().assemble(text, source, **layout_kw, **kw)
        out[name] = setup.messages
    i18n_active.reset_active_bundle()
    return out
