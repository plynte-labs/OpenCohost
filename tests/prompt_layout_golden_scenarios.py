"""Scenarios for the legacy prompt-layout golden (ADR-064 kill switch).

``run_all`` assembles each scenario and returns ``{name: messages}``. The golden
fixture ``tests/fixtures/prompt_layout_legacy_golden.json`` was generated by
running this module against commit 6fccf0e, which has no v2 code at all (the
``layout`` keyword does not exist there), so it pins the pre-ADR-064 bytes.
``layout_kw`` is ``{}`` for that commit and ``{"layout": "legacy"}`` for a tree
that has the switch.
"""
